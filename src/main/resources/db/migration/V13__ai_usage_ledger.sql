-- Metadata-only usage ledger. No prompts, answers, credentials or raw provider bodies.
CREATE TABLE ai_usage_call (
    id VARCHAR(36) NOT NULL PRIMARY KEY,
    trace_id VARCHAR(64) NULL,
    user_id BIGINT NULL,
    purpose VARCHAR(32) NOT NULL,
    configuration_id BIGINT NULL,
    configuration_version BIGINT NULL,
    provider VARCHAR(32) NOT NULL,
    configuration_name VARCHAR(128) NOT NULL,
    key_suffix VARCHAR(16) NOT NULL,
    model VARCHAR(128) NOT NULL,
    actual_model VARCHAR(128) NULL,
    currency VARCHAR(8) NULL,
    input_price DECIMAL(24,10) NULL,
    cached_input_price DECIMAL(24,10) NULL,
    output_price DECIMAL(24,10) NULL,
    business_outcome VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    upstream_outcome VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    upstream_requests INT NOT NULL DEFAULT 0,
    input_tokens BIGINT NOT NULL DEFAULT 0,
    cached_input_tokens BIGINT NOT NULL DEFAULT 0,
    output_tokens BIGINT NOT NULL DEFAULT 0,
    usage_complete TINYINT NOT NULL DEFAULT 0,
    estimated_cost DECIMAL(30,12) NULL,
    created_at DATETIME(3) NOT NULL,
    completed_at DATETIME(3) NULL,
    duration_ms BIGINT NOT NULL DEFAULT 0,
    KEY idx_ai_usage_created (created_at),
    KEY idx_ai_usage_user_created (user_id, created_at),
    KEY idx_ai_usage_config_created (configuration_id, created_at),
    KEY idx_ai_usage_pending (upstream_outcome, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE ai_usage_attempt (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    call_id VARCHAR(36) NOT NULL,
    attempt_no INT NOT NULL,
    http_status INT NULL,
    outcome VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    usage_known TINYINT NOT NULL DEFAULT 0,
    input_tokens BIGINT NULL,
    cached_input_tokens BIGINT NULL,
    output_tokens BIGINT NULL,
    response_id VARCHAR(255) NULL,
    actual_model VARCHAR(128) NULL,
    created_at DATETIME(3) NOT NULL,
    completed_at DATETIME(3) NULL,
    duration_ms BIGINT NOT NULL DEFAULT 0,
    UNIQUE KEY uk_ai_usage_attempt (call_id, attempt_no),
    KEY idx_ai_usage_attempt_created (created_at),
    CONSTRAINT fk_ai_usage_attempt_call FOREIGN KEY (call_id) REFERENCES ai_usage_call(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
