import { test, expect } from '@playwright/test'
import { ACCOUNTS, login } from './helpers/ui.js'

test('真实服务：智能草稿、补充信息、内部隔离、重开及知识审核闭环', async ({ page, browser }, testInfo) => {
  test.setTimeout(180_000)
  const context = await browser.newContext({ baseURL: testInfo.project.use.baseURL, ignoreHTTPSErrors: true })
  const staff = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  staff.on('pageerror', error => errors.push(error.message))
  const marker = `验收 VPN ${Date.now()}`
  const internal = `内部核查 ${marker}`
  try {
    await login(page, ACCOUNTS.employee)
    await page.goto('/tickets/create')
    await page.getByLabel('自然语言描述问题').fill(`${marker} 连不上`)
    await page.getByTestId('generate-draft').click()
    await expect(page.getByTestId('apply-draft')).toBeVisible()
    await expect(page).toHaveURL(/\/tickets\/create$/)
    await page.getByTestId('apply-draft').click()
    await expect(page.getByTestId('ticket-title')).toHaveValue(new RegExp(marker))
    await expect(page).toHaveURL(/\/tickets\/create$/)
    await page.getByTestId('ticket-submit').click()
    await expect(page).toHaveURL(/\/tickets\/\d+$/)
    const id = page.url().match(/\/tickets\/(\d+)$/)[1]
    await expect(page.getByTestId('ticket-status')).toHaveText('待接单')
    await page.getByLabel('工单回复').fill('今天上午开始，只有我受影响，提示连接超时，重启客户端后未恢复。')
    await page.getByTestId('send-reply').click()
    await expect(page.getByText('今天上午开始，只有我受影响，提示连接超时，重启客户端后未恢复。', { exact: true })).toBeVisible()
    await page.getByLabel('上传附件', { exact: true }).setInputFiles({ name: 'vpn-error.txt', mimeType: 'text/plain', buffer: Buffer.from('VPN timeout example') })
    await expect(page.getByRole('link', { name: 'vpn-error.txt' })).toBeVisible()
    const attachment = await page.request.get(await page.getByRole('link', { name: 'vpn-error.txt' }).getAttribute('href'))
    expect(attachment.ok()).toBeTruthy()
    expect(await attachment.text()).toBe('VPN timeout example')
    // Cross the old 2 MB reverse-proxy limit while remaining within the 5 MB file limit.
    await page.getByLabel('上传附件', { exact: true }).setInputFiles({ name: 'diagnostic-3mb.txt', mimeType: 'text/plain', buffer: Buffer.alloc(3 * 1024 * 1024, 0x61) })
    await expect(page.getByRole('link', { name: 'diagnostic-3mb.txt' })).toBeVisible()

    await login(staff, ACCOUNTS.support)
    await staff.goto(`/tickets/${id}`)
    await staff.getByTestId('action-claim').click()
    await staff.getByRole('button', { name: '确认接单', exact: true }).click()
    await expect(staff.getByTestId('ticket-status')).toHaveText('处理中')
    await staff.locator('label.el-radio-button').filter({ hasText: '内部备注' }).click()
    await staff.getByLabel('工单回复').fill(internal)
    await staff.getByTestId('send-reply').click()
    await expect(staff.getByText(internal, { exact: true })).toBeVisible()
    await staff.getByRole('button', { name: '生成处理建议', exact: true }).click()
    await expect(staff.getByRole('button', { name: '填入回复框', exact: true })).toBeVisible()
    await staff.getByRole('button', { name: '填入回复框', exact: true }).click()
    await expect(staff.getByLabel('工单回复')).not.toHaveValue('')
    // Applying a suggestion fills the editor; sending is still a separate user action.
    await staff.getByLabel('工单回复').fill('请补充 VPN 客户端版本号。')
    await staff.getByTestId('send-reply').click()
    await staff.getByRole('button', { name: '请求员工补充信息', exact: true }).click()
    await staff.getByLabel('处理说明').fill('请补充客户端版本号和完整错误代码。')
    await staff.getByTestId('action-confirm').click()
    await expect(staff.getByTestId('ticket-status')).toHaveText('待补充信息')

    await page.reload()
    await expect(page.getByText(internal, { exact: true })).toHaveCount(0)
    const replies = await (await page.request.get(`/api/tickets/${id}/replies`)).json()
    expect(replies.data.every(reply => reply.visibility === 'PUBLIC')).toBeTruthy()
    await page.getByRole('button', { name: '我已补充，请继续处理', exact: true }).click()
    await page.getByLabel('处理说明').fill('客户端 1.0，错误代码 619。')
    await page.getByTestId('action-confirm').click()
    await expect(page.getByTestId('ticket-status')).toHaveText('处理中')

    await staff.reload()
    await staff.getByTestId('action-resolve').click()
    await staff.getByLabel('处理说明').fill('更新客户端配置，重新连接并确认 VPN 可以访问内部服务。')
    await staff.getByTestId('action-confirm').click()
    await expect(staff.getByTestId('ticket-status')).toHaveText('已解决')
    await page.reload()
    await page.getByRole('button', { name: '问题未解决', exact: true }).click()
    await page.getByLabel('处理说明').fill('连接恢复后再次断开，请继续排查。')
    await page.getByTestId('action-confirm').click()
    await expect(page.getByTestId('ticket-status')).toHaveText('处理中')
    await staff.reload()
    await staff.getByTestId('action-resolve').click()
    await staff.getByLabel('处理说明').fill('核对并更新客户端版本，持续验证连接和内部服务访问正常。')
    await staff.getByTestId('action-confirm').click()
    await expect(staff.getByTestId('ticket-status')).toHaveText('已解决')
    await staff.getByRole('button', { name: '整理为知识草稿', exact: true }).click()
    await staff.getByPlaceholder('适用环境，例如 Windows 11 / 公司 VPN').fill('Windows 11 / 企业 VPN')
    await staff.getByRole('button', { name: '生成草稿', exact: true }).click()
    await expect(staff).toHaveURL(/\/kb\?draftId=\d+$/)
    const review = staff.getByRole('dialog', { name: '审核知识草稿', exact: true })
    await expect(review).toBeVisible()
    await review.locator('.el-form-item').filter({ hasText: '标题' }).getByRole('textbox').fill(marker)
    await review.locator('.el-form-item').filter({ hasText: '发布分类' }).locator('.el-select').click()
    await staff.getByRole('option', { name: 'E2E 网络与远程办公', exact: true }).click()
    expect((await page.request.get('/api/kb/drafts')).status()).toBe(403)
    const unreviewed = await (await page.request.get('/api/kb/search', { params: { q: marker } })).json()
    expect(unreviewed.data.total).toBe(0)
    await staff.screenshot({ path: testInfo.outputPath('real-knowledge-review.png'), fullPage: true })
    await review.getByRole('button', { name: '审核并发布', exact: true }).click()
    await staff.getByRole('button', { name: '确认发布', exact: true }).click()
    await expect(review).not.toBeVisible()
    const published = await (await page.request.get('/api/kb/search', { params: { q: marker } })).json()
    expect(published.data.total).toBe(1)

    await page.reload()
    await page.getByTestId('action-close').click()
    await page.getByTestId('action-confirm').click()
    await expect(page.getByTestId('ticket-status')).toHaveText('已关闭')
    expect(errors).toEqual([])
  } finally { await context.close().catch(() => {}) }
})
